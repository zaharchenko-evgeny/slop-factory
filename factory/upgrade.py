#!/usr/bin/env python3
# /// script
# requires-python = ">=3.12"
# dependencies = ["pyyaml>=6"]
# ///
"""What changed in the engine's template/ since a project's engine version (ADR-0016).

Usage: upgrade.py --diff [--from REF|DIR]   unified diff, template at REF (default: the project's `engine`) → installed,
                                            for the paths the project has; names each file the project changed
       upgrade.py --apply PATH              copy the installed template's PATH into the project
       upgrade.py --generate-template       rewrite template/'s generated parts from workflows/nodes.yaml
Nothing in the project is written without --apply.
"""
import argparse
import difflib
import json
import subprocess
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config  # noqa: E402
import workflow  # noqa: E402

TEMPLATE = "template"
MARKER = "# --- generated by `factory/upgrade.py --generate-template`; do not edit below this line\n"


def template_root():
    return config.engine_root() / TEMPLATE


def read_dir(root):
    """{relative path: text} of every file under root."""
    root = Path(root)
    return {p.relative_to(root).as_posix(): p.read_text() for p in sorted(root.rglob("*")) if p.is_file()}


def template_at(ref):
    """The template of an older engine: a directory, or a git ref of the engine checkout."""
    if Path(ref).is_dir():
        return read_dir(ref)
    git = ["git", "-C", str(config.engine_root())]
    names = subprocess.run([*git, "ls-tree", "-r", "--name-only", ref, "--", TEMPLATE],
                           capture_output=True, text=True)
    if names.returncode:
        raise ValueError(f"no template at {ref!r}: {names.stderr.strip() or 'not a git ref of the engine'}")
    return {name.removeprefix(f"{TEMPLATE}/"): subprocess.run([*git, "show", f"{ref}:{name}"], capture_output=True,
                                                              text=True, check=True).stdout
            for name in names.stdout.split()}


def diff(project_root, old, new):
    """(unified diff old → new over the paths the project has, paths the project changed from the old template)."""
    out, edited = [], []
    for rel in sorted(set(old) | set(new)):
        path = Path(project_root) / rel
        if not path.is_file():
            continue
        if old.get(rel) != new.get(rel):
            out += difflib.unified_diff((old.get(rel) or "").splitlines(True), (new.get(rel) or "").splitlines(True),
                                        f"a/{rel}", f"b/{rel}")
        if rel in old and path.read_text() != old[rel]:
            edited.append(rel)
    return "".join(out), edited


def generated(header_text, nodes):
    """(template factory.project.yaml text, workflows/delivery.yaml text) for a header and the engine's nodes."""
    header_text = header_text.split(MARKER, 1)[0]
    project, wf = workflow.migrate(nodes, yaml.safe_load(header_text))
    sections = {k: project[k] for k in ("environments", "workflow", "states", "commands") if k in project}
    return header_text + MARKER + workflow.dump(sections), workflow.dump(wf)


def generate_template():
    root = template_root()
    nodes = yaml.safe_load((config.engine_root() / "workflows/nodes.yaml").read_text())
    descriptor, delivery = generated((root / config.PROJECT_DESCRIPTOR).read_text(), nodes)
    (root / config.PROJECT_DESCRIPTOR).write_text(descriptor)
    (root / workflow.WORKFLOW_PATH).parent.mkdir(parents=True, exist_ok=True)
    (root / workflow.WORKFLOW_PATH).write_text(delivery)


def main(argv):
    p = argparse.ArgumentParser(prog="factory upgrade")
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--diff", action="store_true")
    mode.add_argument("--apply", metavar="PATH")
    mode.add_argument("--generate-template", action="store_true")
    p.add_argument("--from", dest="ref")
    try:
        a = p.parse_args(argv)
    except SystemExit:
        return 2
    project_root, new = config.team_root(), read_dir(template_root())
    if a.generate_template:
        generate_template()
        return 0
    if a.apply:
        if a.apply not in new:
            print(f"upgrade: {a.apply} is not a template file", file=sys.stderr)
            return 1
        (project_root / a.apply).parent.mkdir(parents=True, exist_ok=True)
        (project_root / a.apply).write_text(new[a.apply])
        print(json.dumps({"applied": a.apply}))
        return 0
    descriptor = project_root / config.PROJECT_DESCRIPTOR
    ref = a.ref or str((yaml.safe_load(descriptor.read_text()) or {}).get("engine", "")) if descriptor.is_file() else a.ref
    if not ref:
        print("upgrade: name the old engine with --from REF|DIR (the project has no `engine`)", file=sys.stderr)
        return 2
    try:
        old = template_at(ref)
    except ValueError as e:
        print(f"upgrade: {e}", file=sys.stderr)
        return 2
    text, edited = diff(project_root, old, new)
    print(text, end="")
    for rel in edited:
        print(f"# edited: {rel} differs from the template at {ref}; `factory upgrade --apply {rel}` replaces it")
    return 0


if __name__ == "__main__":
    sys.exit(main(config.pop_team(sys.argv[1:])))
